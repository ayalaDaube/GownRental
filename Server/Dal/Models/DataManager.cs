using System;
using System.Collections.Generic;
using Microsoft.EntityFrameworkCore;

namespace Dal.Models;

public partial class DataManager : DbContext
{
    public DataManager(DbContextOptions<DataManager> options)
        : base(options)
    {
    }

    public virtual DbSet<AppUser> AppUsers { get; set; }

    public virtual DbSet<Appointment> Appointments { get; set; }

    public virtual DbSet<Customer> Customers { get; set; }

    public virtual DbSet<GownModel> GownModels { get; set; }

    public virtual DbSet<ModelDetails> ModelDetails { get; set; }

    public virtual DbSet<Rental> Rentals { get; set; }

    public virtual DbSet<RentalDetails> RentalDetails { get; set; }

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<AppUser>(entity =>
        {
            entity.ToTable("AppUser");
            entity.HasKey(e => e.Id);

            entity.Property(e => e.Username).HasMaxLength(50);
            entity.Property(e => e.PasswordHash).HasMaxLength(200);
            entity.Property(e => e.Role).HasMaxLength(30);

            entity.HasIndex(e => e.Username).IsUnique();
        });

        modelBuilder.Entity<Customer>(entity =>
        {
            entity.ToTable("Customer");
            entity.HasKey(e => e.Id);

            entity.Property(e => e.Id).HasMaxLength(9).IsUnicode(false);
            entity.Property(e => e.Name).HasMaxLength(60);
            entity.Property(e => e.Phone).HasMaxLength(15).IsUnicode(false);
            entity.Property(e => e.Email).HasMaxLength(100).IsUnicode(false);
        });

        modelBuilder.Entity<Appointment>(entity =>
        {
            entity.ToTable("Appointment");
            entity.HasKey(e => e.Id);

            entity.Property(e => e.CustomerId).HasMaxLength(9).IsUnicode(false);
            entity.Property(e => e.Hour).HasPrecision(0);

            // Booking checks that the slot is still free at the moment it is saved. If someone else booked it
            // in between, the update affects no row and fails with a concurrency error (answered as 409).
            entity.Property(e => e.IsAvailable).IsConcurrencyToken();

            // A slot is identified by its date and hour; a customer is attached when it is booked.
            entity.HasIndex(e => new { e.Date, e.Hour }).IsUnique();

            entity.HasOne(d => d.Customer).WithMany(p => p.Appointments)
                .HasForeignKey(d => d.CustomerId)
                .OnDelete(DeleteBehavior.ClientSetNull);
        });

        modelBuilder.Entity<GownModel>(entity =>
        {
            entity.ToTable("GownModel");
            entity.HasKey(e => e.Id);

            // Ids are assigned by the application, not generated by the database.
            entity.Property(e => e.Id).ValueGeneratedNever();
            entity.Property(e => e.Name).HasMaxLength(60);
            entity.Property(e => e.Color).HasMaxLength(30);
            entity.Property(e => e.Description).HasMaxLength(200);
            entity.Property(e => e.ImageUrl).HasMaxLength(500);
        });

        modelBuilder.Entity<ModelDetails>(entity =>
        {
            entity.HasKey(e => e.GownId);

            entity.Property(e => e.GownId).ValueGeneratedNever();

            entity.HasOne(d => d.Model).WithMany(p => p.ModelDetails)
                .HasForeignKey(d => d.ModelId)
                .OnDelete(DeleteBehavior.ClientSetNull);
        });

        modelBuilder.Entity<Rental>(entity =>
        {
            entity.ToTable("Rental");
            entity.HasKey(e => e.Id);

            entity.Property(e => e.CustomerId).HasMaxLength(9).IsUnicode(false);

            entity.HasIndex(e => e.EventDate);

            entity.HasOne<Customer>().WithMany(p => p.Rentals)
                .HasForeignKey(d => d.CustomerId)
                .OnDelete(DeleteBehavior.Restrict);
        });

        modelBuilder.Entity<RentalDetails>(entity =>
        {
            entity.HasKey(e => e.Id);

            entity.HasOne<Rental>().WithMany()
                .HasForeignKey(d => d.RentalId)
                .OnDelete(DeleteBehavior.Restrict);

            entity.HasOne<ModelDetails>().WithMany()
                .HasForeignKey(d => d.GownId)
                .OnDelete(DeleteBehavior.Restrict);
        });

        OnModelCreatingPartial(modelBuilder);
    }

    partial void OnModelCreatingPartial(ModelBuilder modelBuilder);
}
